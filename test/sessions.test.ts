import test, { after } from 'node:test';
import assert from 'node:assert/strict';
import { databaseFixture, cleanupDatabases } from './database.js';
import { SessionService } from '../apps/server/src/server/sessions.js';

after(cleanupDatabases);
test('Session has exactly one coordinator, immutable worker roles and atomic assignment claims', async ()=>{
  const {store}=await databaseFixture();
  const sessions=new SessionService(store.pool);
  const coordinator:any=await sessions.call('sessions_create',{title:'SWE Team',objective:'Prototype an API'});
  const id=coordinator.sessionId;
  assert.equal(coordinator.briefing.participant.role,'coordinator');
  const c={sessionId:id,participantId:coordinator.participantId,credential:coordinator.credential};
  const first:any=await sessions.call('sessions_assign',{...c,title:'Backend',brief:'Implement storage contract',priority:10});
  const second:any=await sessions.call('sessions_assign',{...c,title:'Review',brief:'Review contract against requirements',priority:5});
  const [w1,w2]:any[]=await Promise.all([sessions.call('sessions_join',{sessionId:id}),sessions.call('sessions_join',{sessionId:id})]);
  assert.notEqual(w1.participantId,w2.participantId);
  assert.equal(new Set([w1.briefing.currentAssignments[0]?.id,w2.briefing.currentAssignments[0]?.id]).size,2);
  assert.deepEqual(new Set([first.assignmentId,second.assignmentId]),new Set([w1.briefing.currentAssignments[0]?.id,w2.briefing.currentAssignments[0]?.id]));
  assert.equal(w1.briefing.participant.role,'worker');
  assert.ok(!JSON.stringify(await sessions.get(id)).includes(w1.credential),'Dashboard should not disclose credentials');
  const worker={sessionId:id,participantId:w1.participantId,credential:w1.credential};
  await assert.rejects(sessions.call('sessions_assign',{...worker,title:'Takeover',brief:'Should be denied'}),(e:any)=>e.code==='FORBIDDEN');
  await assert.rejects(sessions.call('sessions_close',worker),(e:any)=>e.code==='FORBIDDEN');
  await assert.rejects(sessions.call('sessions_sync',{...worker,credential:'f'.repeat(64)}),(e:any)=>e.code==='FORBIDDEN');
  await assert.rejects(sessions.call('sessions_claim',worker),(e:any)=>e.code==='INVALID_STATE');
  await sessions.call('sessions_submit',{...worker,assignmentId:w1.briefing.currentAssignments[0].id,status:'submitted',report:'Implemented and tested'});
  assert.equal((await sessions.get(id)).assignments.find((a:any)=>a.id===w1.briefing.currentAssignments[0].id).status,'submitted');
  await assert.rejects(sessions.call('sessions_submit',{...worker,assignmentId:w2.briefing.currentAssignments[0].id,status:'submitted',report:'Cannot submit others'}),(e:any)=>e.code==='INVALID_STATE');
  await sessions.call('sessions_review',{...c,assignmentId:w1.briefing.currentAssignments[0].id,decision:'accepted',feedback:'Looks good'});
  await sessions.call('sessions_set_summary',{...c,summary:'Contract v1 accepted.'});
  const resumed:any=await sessions.call('sessions_sync',worker);
  assert.equal(resumed.session.summary,'Contract v1 accepted.');
  assert.equal(resumed.currentAssignments.length,0);
  await sessions.call('sessions_close',c);
  await assert.rejects(sessions.call('sessions_join',{sessionId:id}),(e:any)=>e.code==='INVALID_STATE');
  assert.equal((await sessions.get(id)).status,'closed');
});

test('Worker cannot bypass blocked or submitted work; requeued work can be safely reclaimed',async()=>{
  const {store}=await databaseFixture();
  const service=new SessionService(store.pool);
  const coord:any=await service.create({title:'Handoff Test',objective:'Review test reports'});
  const c={sessionId:coord.sessionId,participantId:coord.participantId,credential:coord.credential};
  const task:any=await service.assign({...c,title:'Check service',brief:'Submit report'});
  const w:any=await service.join({sessionId:coord.sessionId});
  const wi={sessionId:coord.sessionId,participantId:w.participantId,credential:w.credential};
  await service.submit({...wi,assignmentId:task.assignmentId,status:'blocked',report:'Needs fixture'});
  assert.equal((await service.sync(wi)).currentAssignments[0].status,'blocked');
  await assert.rejects(service.claim(wi),(e:any)=>e.code==='INVALID_STATE');
  await service.submit({...wi,assignmentId:task.assignmentId,status:'submitted',report:'Fixture ready'});
  await service.review({...c,assignmentId:task.assignmentId,decision:'requeue',feedback:'Add race test'});
  assert.equal((await service.get(coord.sessionId)).assignments[0].status,'queued');
  const claimed=await service.claim(wi);
  assert.equal(claimed.assignmentId,task.assignmentId);
  assert.equal((await service.get(coord.sessionId)).assignments[0].assigneeId,w.participantId);
});

test('Coordinator can recover abandoned worker tasks and event cursors retain missed handoffs',async()=>{
  const {store}=await databaseFixture();
  const svc=new SessionService(store.pool);
  const coordinator:any=await svc.create({title:'Recovery',objective:'Make work resumable'});
  const c={sessionId:coordinator.sessionId,participantId:coordinator.participantId,credential:coordinator.credential};
  const job:any=await svc.assign({...c,title:'Implement parser',brief:'Write and test parser'});
  const worker:any=await svc.join({sessionId:c.sessionId});
  const w={sessionId:c.sessionId,participantId:worker.participantId,credential:worker.credential};
  const start:any=await svc.updates({...w});
  const cursor=start.nextCursor;
  await svc.message({...c,body:'Architecture decision: strict parsing only.'});
  const recent:any=await svc.updates({...w,afterEventId:cursor});
  assert.equal(recent.events.filter((e:any)=>e.body.includes('strict parsing')).length,1);
  assert.equal(recent.hasMore,false);
  assert.ok(BigInt(recent.nextCursor)>BigInt(cursor));
  await svc.requeue({...c,assignmentId:job.assignmentId,reason:'Original conversation lost state.'});
  const replacement:any=await svc.join({sessionId:c.sessionId});
  assert.equal(replacement.briefing.currentAssignments[0].id,job.assignmentId);
  assert.notEqual(replacement.participantId,worker.participantId);
  await assert.rejects(svc.submit({...w,assignmentId:job.assignmentId,status:'submitted',report:'Stale update'}),(e:any)=>e.code==='INVALID_STATE');
});
